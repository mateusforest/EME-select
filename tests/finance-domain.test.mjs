test('operation cancellation is atomic and keeps original entries and reason, never partial edits', () => {
  let state = operation(account(emptyFinance()))
  assert.throws(() => command(state, 'entry.cancel', { id: state.entries[0].id, reason: 'Reversão' }), /operação/)
  state = command(state, 'operation.cancel', { id: state.operations[0].id, reason: 'Contrato desfeito' })
  assert.equal(state.entries.length, 3)
  assert.equal(state.operations[0].status, 'cancelled')
  assert.ok(state.entries.every(item => item.status === 'cancelled' && item.cancelReason === 'Contrato desfeito'))
  assert.equal(financeReport(state, period).dre.combined.netProfitCents, 0)
})

