test('partner split requires full allocation, rounds to exact total and respects protected cash', () => {
  let state = settle(entry(account(emptyFinance()), { amountCents: 101 }))
  state = command(state, 'partner.save', { name: 'Sócio A', shareBps: 3333 })
  assert.equal(financeReport(state, period).distribution.ready, false)
  state = command(state, 'partner.save', { name: 'Sócio B', shareBps: 3333 })
  state = command(state, 'partner.save', { name: 'Sócio C', shareBps: 3334 })
  let report = financeReport(state, period)
  assert.equal(report.distribution.eligibleCents, 101)
  assert.equal(report.distribution.shares.reduce((total, item) => total + item.amountCents, 0), 101)
  assert.throws(() => command(state, 'partner.save', { name: 'Sócio extra', shareBps: 1 }), /100%/)
  state = command(state, 'settings.save', { cashTargetCents: 50 })
  report = financeReport(state, period)
  assert.equal(report.distribution.eligibleCents, 51)
  assert.equal(report.distribution.shares.reduce((total, item) => total + item.amountCents, 0), 51)
})

