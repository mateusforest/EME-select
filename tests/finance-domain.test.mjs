import test from 'node:test'
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { applyFinanceCommand, emptyFinance, financeReport, percentCents } from '../shared/finance.mjs'

const actorId = randomUUID(), brokerId = randomUUID(), propertyId = randomUUID()
const context = { actorId, now: '2026-09-16T18:00:00Z', members: [{ id: brokerId, name: 'Corretor real', role: 'corretor', active: true }], properties: [{ id: propertyId, title: 'Imóvel real' }] }
const period = { from: '2026-09-01', to: '2026-09-30', asOf: '2026-09-16' }
const command = (state, type, data) => applyFinanceCommand(state, { type, data }, context)
const account = (state, amount = 0, data = {}) => command(state, 'account.save', { name: 'Conta principal', kind: 'bank', openingDate: '2026-01-01', openingBalanceCents: amount, ...data })
const entry = (state, data = {}) => command(state, 'entry.save', { description: 'Honorários de venda', category: 'sale_fee', amountCents: 10000, recognition: 'recognized', competenceDate: '2026-09-01', dueDate: '2026-09-10', behavior: 'variable', ...data })
const settle = (state, item = state.entries.at(-1), data = {}) => command(state, 'entry.settle', { id: item.id, accountId: state.accounts[0].id, settledDate: '2026-09-10', ...data })
const operation = (state, data = {}) => command(state, 'operation.create', { title: 'Venda de imóvel', kind: 'sale', amountCents: 100001, commissionBps: 3333, directCostCents: 5000, reserveBps: 1000, brokerId, propertyId, competenceDate: '2026-09-01', dueDate: '2026-09-10', ...data })

test('empty setup does not invent balances, partners, percentages or return estimates', () => {
  const state = emptyFinance()
  const report = financeReport(state, period)
  assert.equal(state.settings.reserveBps, null)
  assert.equal(report.cash.balanceCents, 0)
  assert.equal(report.cash.targetCents, null)
  assert.equal(report.payback.monthsEstimate, null)
  assert.equal(report.distribution.ready, false)
  assert.deepEqual(report.brokers, [])
})

test('currency uses exact integer cents and basis point rounding, including half cent', () => {
  assert.equal(percentCents(100001, 3333), 33330)
  assert.equal(percentCents(1, 5000), 1)
  assert.equal(percentCents(1_000_000_000_000, 9999), 999900000000)
  assert.throws(() => entry(emptyFinance(), { amountCents: 1.25 }), /inteiro/)
  assert.throws(() => entry(emptyFinance(), { amountCents: -1 }), /inteiro/)
  assert.throws(() => entry(emptyFinance(), { amountCents: Infinity }), /inteiro/)
})

test('DRE competence and bank cash settlement stay separate, including prepaid cash', () => {
  let state = account(emptyFinance())
  state = entry(state, { competenceDate: '2026-10-01', dueDate: '2026-09-10' })
  state = settle(state)
  assert.equal(financeReport(state, period).cash.balanceCents, 10000)
  assert.equal(financeReport(state, period).dre.combined.revenueCents, 0)
  assert.equal(financeReport(state, { ...period, from: '2026-10-01', to: '2026-10-31' }).dre.combined.revenueCents, 10000)
  assert.throws(() => settle(entry(state), undefined, { settledDate: '2026-09-17' }), /futuro/)
})

test('transfers balance individual accounts without revenue, expense, MRR or profit', () => {
  let state = account(emptyFinance(), 100000)
  state = account(state, 20000, { name: 'Conta de reserva' })
  state = entry(state, { category: 'transfer', amountCents: 30000 })
  state = settle(state, undefined, { destinationAccountId: state.accounts[1].id })
  const report = financeReport(state, period)
  assert.deepEqual(report.cash.accounts.map(item => item.balanceCents), [70000, 50000])
  assert.equal(report.cash.balanceCents, 120000)
  assert.equal(report.dre.combined.netProfitCents, 0)
  assert.equal(report.period.paidCents, 0)
  assert.equal(report.period.receivedCents, 0)
  assert.throws(() => settle(entry(state, { category: 'transfer' }), undefined, { destinationAccountId: state.accounts[0].id }), /diferente/)
})

