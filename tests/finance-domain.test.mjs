test('retained management fee reclassifies owner funds without inventing a second bank deposit', () => {
  let state = account(emptyFinance())
  state = settle(entry(state, { category: 'third_party_in', amountCents: 100000, propertyId }))
  state = settle(entry(state, { category: 'third_party_out', amountCents: 90000, propertyId }))
  state = settle(entry(state, { category: 'management_fee_retained', amountCents: 10000, propertyId }))
  const report = financeReport(state, period)
  assert.equal(report.cash.balanceCents, 10000)
  assert.equal(report.cash.thirdPartyHeldCents, 0)
  assert.equal(report.cash.availableCents, 10000)
  assert.equal(report.dre.combined.revenueCents, 10000)
  assert.equal(report.period.receivedCents, 100000)
  assert.equal(report.period.paidCents, 90000)
  assert.equal(report.period.operatingCashCents, 10000)
  assert.throws(() => settle(entry(state, { category: 'management_fee_retained', amountCents: 1, propertyId })), /saldo suficiente/)
  state = command(state, 'entry.cancel', { id: state.entries.at(-1).id, reason: 'Taxa corrigida' })
  assert.equal(financeReport(state, period).cash.balanceCents, 10000)
  assert.equal(financeReport(state, period).cash.thirdPartyHeldCents, 10000)
})

test('retention requires funds by the settlement date and property, and forecasts no new deposit', () => {
  let state = account(emptyFinance())
  state = settle(entry(state, { category: 'third_party_in', amountCents: 100000, propertyId }))
  let pending = entry(state, { category: 'management_fee_retained', amountCents: 10000, propertyId })
  assert.throws(() => settle(pending, undefined, { settledDate: '2026-09-09' }), /saldo suficiente/)
  const otherPropertyId = randomUUID()
  const expandedContext = { ...context, properties: [...context.properties, { id: otherPropertyId, title: 'Outro imóvel' }] }
  pending = applyFinanceCommand(state, { type: 'entry.save', data: { description: 'Taxa de outro imóvel', category: 'management_fee_retained', amountCents: 10000, propertyId: otherPropertyId, competenceDate: '2026-09-01', dueDate: '2026-09-10' } }, expandedContext)
  assert.throws(() => settle(pending), /vinculado a este imóvel/)
  state = command(state, 'recurrence.save', { name: 'Administração retida', category: 'management_fee_retained', amountCents: 10000, startMonth: '2026-09', dueDay: 20, propertyId })
  const report = financeReport(state, period)
  assert.equal(report.mrrCents, 10000)
  assert.equal(report.projections[0].receivableCents, 0)
  assert.equal(report.projections[0].retainedFeesCents, 10000)
  assert.equal(report.projections[0].closingCents, 100000)
  assert.equal(report.projections[0].availableCents, 10000)
})

