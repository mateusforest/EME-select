test('recurring monthly fees generate once per month and projections do not double count', () => {
  let state = account(emptyFinance())
  state = command(state, 'recurrence.save', { name: 'Gestão mensal', category: 'management_fee', amountCents: 10000, startMonth: '2026-09', dueDay: 20, active: true })
  const recurrenceId = state.recurrences[0].id
  state = command(state, 'recurrence.generate', { id: recurrenceId, month: '2026-09' })
  state = command(state, 'recurrence.generate', { id: recurrenceId, month: '2026-09' })
  assert.equal(state.entries.length, 1)
  let report = financeReport(state, period)
  assert.equal(report.mrrCents, 10000)
  assert.equal(report.arrCents, 120000)
  assert.equal(report.projections[0].receivableCents, 10000)
  assert.equal(report.projections[1].receivableCents, 10000)
  assert.equal(report.dre.combined.revenueCents, 0)
  state = settle(state)
  report = financeReport(state, period)
  assert.equal(report.projections[0].receivableCents, 0)
  assert.equal(report.dre.combined.revenueCents, 10000)
  state = command(state, 'entry.cancel', { id: state.entries[0].id, reason: 'Competência cancelada' })
  state = command(state, 'recurrence.generate', { id: recurrenceId, month: '2026-09' })
  assert.equal(state.entries.length, 1)
})

test('unmaterialized recurring expenses project while one-off rents and thirds never inflate MRR', () => {
  let state = account(emptyFinance(), 10000)
  for (const [category, amountCents] of [['software', 25000], ['third_party_in', 100000], ['rental_fee', 10000]]) {
    state = command(state, 'recurrence.save', { name: `Recorrência ${category}`, category, amountCents, startMonth: '2026-09', endMonth: '2026-09', dueDay: 20 })
  }
  state = command(state, 'settings.save', { cashTargetCents: 50000 })
  const report = financeReport(state, period)
  assert.equal(report.mrrCents, 0)
  assert.equal(report.projections[0].closingCents, 95000)
  assert.equal(report.projections[0].availableCents, -5000)
  assert.equal(report.projections[0].belowTarget, true)
  assert.equal(report.projections[1].receivableCents, 0)
})

