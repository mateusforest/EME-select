  await page.screenshot({path:'design/portal-team/overview-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Nova avaliação',exact:true}).click();
  await page.getByLabel('Nome do imóvel',{exact:true}).fill('Casa de verificação');
  await page.getByLabel('Cidade e região').fill('Caxias do Sul');
  await page.getByRole('button',{name:'Cadastrar avaliação'}).click();
  const detail=page.getByRole('dialog');
  await expect(detail).toContainText('Cadastro criado');
  await detail.getByRole('combobox',{name:/^Etapa/}).selectOption('Em avaliação');
  await detail.getByLabel('Observação').fill('Conferir a área e os próximos documentos.');
  await detail.getByRole('button',{name:'Salvar acompanhamento'}).click();
  await expect(detail.locator('.pt-history')).toContainText('Conferir a área');
  await page.screenshot({path:'design/portal-team/dossier-desktop.png'});
  await page.keyboard.press('Escape');
  await page.reload();
  await expect(page.getByRole('button',{name:/Casa de verificação/}).first()).toBeVisible();
  expect(await page.evaluate(()=>Object.keys(localStorage).filter(key=>key.includes('portal')))).toEqual([]);
  checks.push('Database-backed create, note, history, reload; no real data in localStorage');
  await page.getByRole('navigation',{name:'Navegação da equipe'}).getByRole('link',{name:'Equipe e acessos'}).click();
  await page.getByRole('button',{name:'Adicionar pessoa'}).click();
  const form=page.getByRole('dialog');
  await form.getByLabel('Nome',{exact:true}).fill('Corretor de teste');
  await form.getByLabel('E-mail',{exact:true}).fill('broker@example.test');
  await form.getByLabel('Senha inicial').fill('OnlyForTesting-2026-A!');
  await form.getByRole('button',{name:'Criar acesso'}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.pt-team-row').filter({hasText:'Corretor de teste'})).toBeVisible();
  checks.push('Administrator can create staff account');
  const broker=await browser.newContext({viewport:{width:390,height:844}});
  const second=await broker.newPage();
  second.on('pageerror',error=>errors.push(error.message));
  await second.goto(origin+'/portalselect');
  await second.getByLabel('E-mail',{exact:true}).fill('broker@example.test');
  await second.getByLabel('Senha',{exact:true}).fill('OnlyForTesting-2026-A!');
