  await expect(page.getByRole('heading',{name:'Seu acesso começa aqui.'})).toBeVisible();
  await page.screenshot({path:'design/portal-team/setup-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'design/portal-team/setup-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.setViewportSize({width:1440,height:1024});
